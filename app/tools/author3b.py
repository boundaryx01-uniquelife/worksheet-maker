from collections import deque
def hanoi(n,adj=False):
    start=(tuple(range(n,0,-1)),(),());goal=((),(),tuple(range(n,0,-1)))
    def mv(s):
        for i in range(3):
            if not s[i]:continue
            for j in range(3):
                if i==j:continue
                if adj and abs(i-j)!=1:continue
                if not s[j] or s[j][-1]>s[i][-1]:
                    t=[list(x) for x in s];d=t[i].pop();t[j].append(d);yield tuple(tuple(x) for x in t)
    dist={start:0};q=deque([start])
    while q:
        s=q.popleft()
        if s==goal:return dist[s]
        for t in mv(s):
            if t not in dist:dist[t]=dist[s]+1;q.append(t)
