@lru_cache(None)
def tile_ok(n,removed):
    cells=frozenset((r,c) for r in range(n) for c in range(n))-frozenset(removed)
    @lru_cache(None)
    def go(s):
        if not s:return True
        f=min(s)
        for d in ((0,1),(1,0)):
            o=(f[0]+d[0],f[1]+d[1])
            if o in s and go(s-{f,o}):return True
        return False
    return go(cells)
